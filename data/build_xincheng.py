items = []
def num(v):
    v = round(float(v), 2); return int(v) if v == int(v) else v
def dname(d): return {'1': '1"', '2': '2"'}.get(d, d)
def inch(x): return x if x.endswith('"') else x + '"'
def add(cat, name, spec, dia, L, price, disc, mat, fin='', head='', thread='', unit='100支', note='', nut=False):
    it = dict(id=f'xc{len(items):04d}', cat=cat, code='', name=name, spec=spec, material=mat, finish=fin, head=head,
              system='公制' if dia.startswith('M') else '英制', dia=dia, thread=thread, length=str(L), unit=unit,
              price=num(price), disc=str(disc), sup=SUP, note=BASE + (f'（{note}）' if note else ''))
    if nut: it['nut'] = True
    items.append(it)
def parse(tbl):
    lines = [l for l in tbl.strip().splitlines() if l.strip()]
    cols = lines[0].split()
    for ln in lines[1:]:
        r, vals = ln.split(':', 1)
        for c, v in zip(cols, vals.split()):
            if v != '.':
                yield r.strip(), c, float(v)
def bolts(tbl, cat, name, mat, disc, unit, fin='', head='六角', thread='', note='', keep=lambda d, L: True, metric=True):
    for L, d, p in parse(tbl):
        if not keep(d, L): continue
        dd = dname(d); Ls = L if metric else inch(L)
        dv = disc(d, L) if callable(disc) else disc
        nt = note(d, L) if callable(note) else note
        add(cat, name, f'{dd}×{Ls}', dd, Ls, p, dv, mat, fin, head, thread, unit, nt)

def num_l(L):
    a = L.split('-'); n = 0
    for x in a:
        n += eval(x) if '/' in x else float(x)
    return n

