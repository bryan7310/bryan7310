# ── 牙系／直徑／牙型 ──
COARSE = {'2': 0.4, '2.5': 0.45, '3': 0.5, '3.5': 0.6, '4': 0.7, '5': 0.8, '5.5': 0.9, '6': 1.0, '7': 1.0, '8': 1.25,
          '10': 1.5, '12': 1.75, '14': 2.0, '16': 2.0, '18': 2.5, '20': 2.5, '22': 2.5, '24': 3.0}
def info(spec):
    m = re.match(r'M(\d+(?:\.\d+)?)', spec)
    if m:
        p = re.search(r'P(\d+\.\d+)', spec)
        th = '公制粗牙'
        if p and COARSE.get(m.group(1)) and float(p.group(1)) != COARSE[m.group(1)]:
            th = '公制細牙' if float(p.group(1)) < COARSE[m.group(1)] else '特殊牙距'
        return '公制', 'M' + m.group(1), th
    m = re.match(r'(\d+)#', spec)
    if m: return '英制', m.group(1) + '#', '番數機械牙'
    m = re.match(r'(\d+/\d+|1")', spec)
    if m:
        rest = spec[len(m.group(1)):]
        th = 'UNC/UNF' if rest.startswith('NC-NF') else 'UNC' if rest.startswith('NC') or rest.startswith('-12') else \
             'UNF' if rest.startswith('NF') else 'BC' if rest.startswith('BC') else '英制'
        return '英制', m.group(1), th
    return '', '', ''

