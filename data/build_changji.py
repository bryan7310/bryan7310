def add(cat, name, spec, dia, L, price, disc, mat, fin='', note=NOTE, nut=True, unit='100個'):
    it = dict(id=f'cj{len(items):04d}', cat=cat, code='', name=name, spec=spec, material=mat, finish=fin, head='',
              system='公制' if dia.startswith('M') else '英制', dia=dia, thread='公制' if dia.startswith('M') else '英制', length=L, unit=unit,
              price=num(price), disc=str(disc), sup=SUP, note=note)
    if nut: it['nut'] = True
    items.append(it)

