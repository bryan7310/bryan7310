items = []
def parse(tbl):
    lines = [l for l in tbl.strip().splitlines() if l.strip()]
    cols = lines[0].split()
    for ln in lines[1:]:
        r, vals = ln.split(':', 1)
        for c, v in zip(cols, vals.split()):
            if v != '.':
                yield r.strip(), c, v
def num(v):
    v = float(v); return int(v) if v == int(v) else v
def inch(x): return x if x.endswith('"') else x + '"'
def add(cat, name, spec, dia, length, price, unit, disc, mat='SUS304', head='', thread='', nut=False, extra=None, note=None):
    it = dict(id=f'dq{len(items):04d}', cat=cat, code='', name=name, spec=spec, material=mat, finish='', head=head,
              system='公制' if str(dia).startswith('M') else '英制' if dia else '', dia=dia, thread=thread, length=str(length),
              unit=unit, price=num(price), disc=str(disc), sup=SUP, batch='東日2', note=note or NOTE)
    if nut: it['nut'] = True
    if extra: it.update(extra)
    items.append(it)
def grid(tbl, cat, name, unit, disc, head='', mat='SUS304', note=None):
    for r, c, v in parse(tbl):
        Ls = c if r.startswith('M') else inch(c)
        add(cat, name, f'{r}×{Ls}', r, Ls, v, unit, disc, mat, head, note=note)

