def num(v):
    v = float(v); return int(v) if v == int(v) else v
def inch(x): return x if x.endswith('"') else x + '"'
def norm_len(L):
    L = L.replace('"', '').replace(' ', '-')
    return L if L.endswith('mm') else inch(L)
def add(cat, name, dia, L, price, disc, mat, head='', thread='', box=None, extra_note=''):
    if price in (None, '.', ''): return
    Ls = L if (dia.startswith('M') or L.endswith('mm') or not L) else norm_len(L)
    note = NOTE + (f'（每盒{box}）' if box else '') + extra_note
    items.append(dict(id=f'jt{len(items):04d}', cat=cat, code='', name=name, spec=f'{dia}×{Ls}' if Ls else dia, material=mat,
                      finish='', head=head, system='公制' if dia.startswith('M') else '英制', dia=dia, thread=thread,
                      length=Ls.replace('mm', ''), unit='100支', price=num(price), disc=str(disc), sup=SUP, note=note))
def grid(tbl, cat, name, disc, mat, head='', thread='', mm=False, disc_fn=None):
    lines = [l for l in tbl.strip().splitlines() if l.strip()]
    cols = lines[0].split()
    for ln in lines[1:]:
        r, vals = ln.split(':', 1); r = r.strip()
        for c, v in zip(cols, vals.split()):
            if v != '.':
                add(cat, name, r, c if (mm or r.startswith('M')) else c, v, disc_fn(r) if disc_fn else disc, mat, head, thread)

