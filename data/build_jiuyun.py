items = []

def inch(v):
    """英制長度補上 " 方便辨識與排序：1 → 1"、3/4 → 3/4"。"""
    v = str(v)
    return v if v.endswith('"') else v + '"'

def add(cat, name, spec, material, head, thread, length, price, disc, unit='100支'):
    items.append(dict(cat=cat, name=name, spec=spec, material=material, head=head,
                      thread=thread, length=str(length), unit=unit, price=price, disc=str(disc)))

def cell_prices(v, heads):
    """格子可能寫「丸16.5 皿18.5」這種分頭型價格，用 dict 表示。"""
    if isinstance(v, dict):
        return [(h, p) for h, p in v.items()]
    return [(h, v) for h in heads]

def matrix(cat, name_fmt, material, thread, lengths, rows, heads_disc, inch_len=False, dia_fmt='{}', mat_by_row=None):
    """rows: {直徑: [價格或 None…]}；heads_disc: {直徑: {頭型: 折數}}"""
    for dia, prices in rows.items():
        hd = heads_disc[dia]
        for L, v in zip(lengths, prices):
            if v is None:
                continue
            for head, p in cell_prices(v, list(hd)):
                if head not in hd:
                    continue
                Ls = inch(L) if inch_len else str(L)
                d = dia_fmt.format(dia)
                add(cat, name_fmt.format(head=head), f'{d}×{Ls}',
                    (mat_by_row or {}).get(dia, material), head, thread, Ls, p, hd[head])

