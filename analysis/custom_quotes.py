COLS = ['編號', '廠商', '日期', '品名', '規格', '材質', '材質群', '表面', '數量', '單價', '模具費', '體積mm3', '加工', '判讀備註']


def build():
    df = pd.DataFrame(Q, columns=COLS)
    df['估計重量g'] = [round(v * RHO[m] / 1000, 2) if v else None for v, m in zip(df['體積mm3'], df['材質群'])]
    # Z1 澤發明列成本結構：工資 + 單重 × 線材價
    z1 = df['編號'] == 'Z1'
    df.loc[z1, '單價'] = round(0.4 + 12.8 / 1000 * 106, 2)
    df['每公斤單價'] = (df['單價'] / df['估計重量g'] * 1000).round(0)
    df['模具攤提每支'] = (df['模具費'].fillna(0) / df['數量']).round(3)
    df['含模具每支'] = (df['單價'] + df['模具攤提每支']).round(3)
    return df.drop(columns='體積mm3')


